import {execFile} from 'node:child_process';
import {promisify} from 'node:util';
import {readFile,writeFile,mkdir,readdir} from 'node:fs/promises';
import assert from 'node:assert/strict';
const exec=promisify(execFile);
const base='http://localhost:8286';const home='/tmp/audit-studio-e2e';const cwd=home+'/workspace';const checks=[];
const api=async(path,method='GET',body)=>{const r=await fetch(base+path,{method,body:body?JSON.stringify(body):undefined});const d=await r.json();assert.ok(r.ok,JSON.stringify(d));return d;};
const processes=async()=>{const {stdout}=await exec('ps',['-eo','pid,args']);return stdout.split('\n').filter(l=>l.includes('/node_modules/.bin/dsh --profile acp --patch '+home+'/dsh/audit-studio.patch.yml')).map(l=>Number(l.trim().split(/\s/)[0]));};
const wait=async(fn)=>{for(let i=0;i<180;i++){if(await fn())return;await new Promise(r=>setTimeout(r,250));}throw new Error('lifecycle wait timeout');};
const {sessionId:id}=await api('/api/agent/new','POST',{cwd});
const prompt=async(message)=>{await api(`/api/agent/${id}`,'POST',{message});await wait(async()=>!(await api(`/api/agent/${id}`)).isStreaming);};
await prompt('lifecycle first turn');
let ids=await processes();assert.equal(ids.length,1);checks.push('one runtime across routes/HMR');
process.kill(ids[0],'SIGKILL');
await wait(async()=>{const next=await processes();return next.length===1&&next[0]!==ids[0];});
checks.push('unexpected crash automatically starts a new child');
await prompt('resumed after crash');
const context=await api(`/api/sessions/${id}/context`);assert.ok(context.messages.filter(m=>m.role==='assistant').length>=2);assert.ok(!context.messages.at(-1).errorMessage);checks.push('existing conversation resumes after runtime crash');
const old=(await processes())[0];
await api('/api/models-config/default','PUT',{systemPromptMode:'append',systemPrompt:'lifecycle config restart marker'});
assert.notEqual((await processes())[0],old);await prompt('after config save');
assert.ok(!(await api(`/api/sessions/${id}/context`)).messages.at(-1).errorMessage);checks.push('configuration save restarts runtime and resumes context');
await api(`/api/sessions/${id}`,'PATCH',{name:'retained rename'});await prompt('after rename');
assert.equal((await api('/api/sessions')).sessions.find(s=>s.id===id).name,'retained rename');checks.push('rename survives subsequent turns');
assert.ok(!(await readFile(home+'/dsh/audit-studio.patch.yml','utf8')).includes('e2e-secret'));checks.push('patch contains no API key');
await api(`/api/sessions/${id}`,'DELETE');
const dirs=await readdir(home+'/dsh/sessions',{withFileTypes:true});for(const dir of dirs)if(dir.isDirectory())assert.ok(!(await readdir(home+'/dsh/sessions/'+dir.name)).includes(id));checks.push('delete removes actual dsh project/session directory');
const {sessionId:activeId}=await api('/api/agent/new','POST',{cwd});
await fetch('http://127.0.0.1:19999/control',{method:'POST',body:JSON.stringify({mode:'hang',hangMs:15000})});
try {
 await api(`/api/agent/${activeId}`,'POST',{message:'delete while streaming'});
 await api(`/api/sessions/${activeId}`,'DELETE');
 await new Promise(r=>setTimeout(r,300));
 assert.ok(!(await api('/api/sessions')).sessions.some(s=>s.id===activeId));
 const files=await readdir(home+'/transcripts');assert.ok(!files.includes(activeId+'.jsonl'));
 checks.push('deleting an active turn never recreates transcript or index');
} finally {await fetch('http://127.0.0.1:19999/control',{method:'POST',body:JSON.stringify({mode:'normal'})});}
await mkdir('docs',{recursive:true});await writeFile('docs/dsh-lifecycle-result.json',JSON.stringify({checks},null,2));
console.log('PASS '+checks.join(', '));
