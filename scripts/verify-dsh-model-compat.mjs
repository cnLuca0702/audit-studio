/** Run against the isolated /tmp/audit-studio-e2e application and local mock. */
import assert from 'node:assert/strict';
import {execFile} from 'node:child_process';
import {promisify} from 'node:util';
import {mkdir,writeFile} from 'node:fs/promises';
const exec=promisify(execFile);
const base='http://localhost:8286';const cwd='/tmp/audit-studio-e2e/workspace';const checks=[];
const api=async(path,method='GET',body)=>{const r=await fetch(base+path,{method,headers:{'Content-Type':'application/json'},body:body?JSON.stringify(body):undefined});const d=await r.json();assert.ok(r.ok,JSON.stringify(d));return d;};
const wait=async(fn)=>{for(let i=0;i<120;i++){if(await fn())return;await new Promise(r=>setTimeout(r,250));}throw new Error('model compatibility timeout');};
const pids=async()=>{const {stdout}=await exec('ps',['-eo','pid,args']);return stdout.split('\n').filter(line=>/^\s*\d+\s+\S*node \S+\/node_modules\/\.bin\/dsh --profile acp --patch \/tmp\/audit-studio-e2e\/dsh\/audit-studio\.patch\.yml$/.test(line)).map(line=>Number(line.trim().split(/\s/)[0]));};
const restart=async()=>{const before=await pids();assert.equal(before.length,1);process.kill(before[0],'SIGKILL');await wait(async()=>{const after=await pids();return after.length===1&&after[0]!==before[0];});};
await api('/api/models-config','PATCH',{provider:'mock',models:[{id:'mock-a',reasoning:true},{id:'mock-b',reasoning:true},{id:'mock-plain',reasoning:false}]});
await api('/api/models-config/default','PUT',{defaultProvider:'mock',defaultModel:'mock-plain',defaultThinkingLevel:'high'});
const plain=await api('/api/agent/new','POST',{cwd});
assert.equal((await api(`/api/agent/${plain.sessionId}`)).thinkingLevel,'off');checks.push('global high does not prevent creating a non-reasoning session');
await api('/api/models-config/default','PUT',{defaultModel:'mock-a',defaultThinkingLevel:'high'});
const reasoning=await api('/api/agent/new','POST',{cwd});const id=reasoning.sessionId;
assert.equal((await api(`/api/agent/${id}`)).thinkingLevel,'high');
await api(`/api/agent/${id}`,'POST',{command:'set_model',provider:'mock',modelId:'mock-plain'});
assert.equal((await api(`/api/agent/${id}`)).thinkingLevel,'off');checks.push('switching to a non-reasoning model clears stale thinking state');
await restart();
await api('/api/agent/new','POST',{sessionId:id,cwd});
await api(`/api/agent/${id}`,'POST',{message:'continue with plain model after crash'});
await wait(async()=>!(await api(`/api/agent/${id}`)).isStreaming);
assert.ok(!(await api(`/api/sessions/${id}/context`)).messages.at(-1).errorMessage);
assert.equal((await (await fetch('http://127.0.0.1:19999/stats')).json()).requests.at(-1).model,'mock-plain');checks.push('non-reasoning model resumes after runtime crash');
await api(`/api/agent/${id}`,'POST',{command:'set_model',provider:'mock',modelId:'mock-a'});
await api(`/api/agent/${id}`,'POST',{command:'set_thinking_level',level:'off'});
await restart();await api('/api/agent/new','POST',{sessionId:id,cwd});
assert.equal((await api(`/api/agent/${id}`)).thinkingLevel,'off');checks.push('explicit off survives runtime restart');
for(const sessionId of [plain.sessionId,id])await api(`/api/sessions/${sessionId}`,'DELETE');
await api('/api/models-config/default','PUT',{defaultModel:'mock-a',defaultThinkingLevel:'low'});
await mkdir('docs',{recursive:true});await writeFile('docs/dsh-model-compat-result.json',JSON.stringify({checks},null,2)+'\n');
console.log('PASS '+checks.join(', '));
