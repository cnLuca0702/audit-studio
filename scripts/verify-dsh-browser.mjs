import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import {writeFile,mkdir} from 'node:fs/promises';
const base=process.env.AUDIT_TEST_URL || 'http://localhost:8286';
const cwd='/tmp/audit-studio-e2e/workspace';
const name='browser-proof-'+Date.now();
const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH || chromium.executablePath(),args:['--no-sandbox']});
const page=await browser.newPage();const checks=[];const errors=[];
page.on('pageerror',e=>errors.push(e.message));
page.setDefaultTimeout(20000);
const json=async(path,method='GET',data)=>{const r=await page.request.fetch(base+path,{method,data});assert.ok(r.ok(),await r.text());return r.json();};
try {
 await page.goto(base);
 await page.getByRole('button',{name:'智能模式',exact:true}).click();
 await json('/api/cwd-history','POST',{cwd});
 const {sessionId}=await json('/api/agent/new','POST',{cwd});
 await json(`/api/sessions/${sessionId}`,'PATCH',{name});
 await page.reload();await page.getByRole('button',{name:'智能模式',exact:true}).click();
 await page.getByText(name,{exact:true}).click();
 const input=page.getByPlaceholder('输入消息，按 Enter 发送');
 await page.waitForFunction(()=>!document.querySelector('textarea')?.disabled,{}, {timeout:30000});
 await input.waitFor();await input.fill('browser first turn');await input.press('Enter');
 await page.getByText('本项目为信息化系统建设项目，总预算为1350万元',{exact:false}).first().waitFor({timeout:60000});
 await page.waitForFunction(()=>!document.querySelector('.typing-indicator'));
 checks.push('browser sends and renders streamed assistant content');
 await page.reload();await page.getByRole('button',{name:'智能模式',exact:true}).click();await page.getByText(name,{exact:true}).click();
 await page.getByText('browser first turn',{exact:true}).waitFor();
 await page.waitForFunction(()=>!document.querySelector('textarea')?.disabled,{}, {timeout:30000});checks.push('refresh reopens persisted conversation');
 await page.getByPlaceholder('输入消息，按 Enter 发送').fill('browser resumed turn');await page.getByPlaceholder('输入消息，按 Enter 发送').press('Enter');
 await page.waitForFunction(()=>!document.querySelector('.typing-indicator'),{},{timeout:60000});
 await page.waitForTimeout(3000);
 const context=await json(`/api/sessions/${sessionId}/context`);
 assert.ok(context.messages.some(m=>m.role==='user'&&JSON.stringify(m.content).includes('browser resumed turn')));checks.push('resume conversation after reload');
 await page.locator('.file-entry').filter({hasText:'outputs'}).click();
 await page.locator('.file-entry').filter({hasText:'spike.docx'}).first().click();
 await page.locator('.file-preview pre').filter({hasText:'中文内容'}).waitFor();checks.push('right panel Word preview');
 await page.getByRole('button',{name:'关闭预览'}).click();
 await page.locator('.file-entry').filter({hasText:'spike.pdf'}).first().click();
 await page.locator('.file-preview iframe').waitFor();checks.push('right panel PDF preview');
 await page.getByText('[Pi 只读] legacy hello',{exact:false}).click();
 assert.ok(await page.getByPlaceholder('Pi 历史会话（只读）').isDisabled());checks.push('legacy conversation input is disabled');
 const stats=await (await fetch('http://127.0.0.1:19999/stats')).json();
 assert.ok(JSON.stringify(stats).includes('e2e-proof'));checks.push('installed skill visible in actual model context');
 assert.deepEqual(errors,[]);checks.push('no browser page errors');
 await mkdir('docs',{recursive:true});await writeFile('docs/dsh-browser-result.json',JSON.stringify({checks,errors},null,2));
 await page.screenshot({path:'/tmp/audit-dsh-browser.png',fullPage:true});
 console.log('PASS '+checks.join(', '));
} catch(error) {await page.screenshot({path:"/tmp/audit-dsh-failure.png",fullPage:true});console.log(await page.locator("body").innerText());throw error;} finally {await browser.close();}
