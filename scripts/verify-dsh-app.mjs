import assert from 'node:assert/strict';
import {readFile,writeFile,mkdir} from 'node:fs/promises';
const base=process.env.AUDIT_TEST_URL || 'http://127.0.0.1:8286';
const cwd=process.env.AUDIT_TEST_CWD || '/tmp/audit-studio-e2e/workspace';
const checks=[];
async function api(path,method='GET',body) {
 const r=await fetch(base+path,{method,headers:body?{'Content-Type':'application/json'}:{},body:body?JSON.stringify(body):undefined});
 const data=await r.json();assert.ok(r.ok,`${method} ${path}: ${JSON.stringify(data)}`);return data;
}
const control=async(mode)=>fetch('http://127.0.0.1:19999/control',{method:'POST',body:JSON.stringify({mode,hangMs:15000})});
const wait=async(fn)=>{for(let i=0;i<120;i++){if(await fn())return;await new Promise(r=>setTimeout(r,250));}throw new Error('wait timeout');};
const {sessionId:id}=await api('/api/agent/new','POST',{cwd});
checks.push('create with dsh sessionId');
const controller=new AbortController();
const response=await fetch(base+`/api/agent/${id}/events`,{signal:controller.signal});
const events=[];let buffer='';
const reader=response.body.getReader();
const stream=(async()=>{try{for(;;){const{value,done}=await reader.read();if(done)break;buffer+=new TextDecoder().decode(value);const blocks=buffer.split('\n\n');buffer=blocks.pop();for(const b of blocks){if(b.startsWith('data: '))events.push(JSON.parse(b.slice(6)));}}}catch(e){if(e.name!=='AbortError')throw e;}})();
const prompt=async(text)=>{await api(`/api/agent/${id}`,'POST',{message:text});await wait(async()=>!(await api(`/api/agent/${id}`)).isStreaming);};
await control('normal');await prompt('first hello');
assert.ok(events.some(e=>e.type==='message_update'));assert.ok(events.some(e=>e.type==='agent_end'));checks.push('streaming SSE uses existing event contract');
await api(`/api/agent/${id}`,'POST',{command:'set_model',provider:'mock',modelId:'mock-b'});
await api(`/api/agent/${id}`,'POST',{command:'set_thinking_level',level:'high'});
assert.equal((await api(`/api/agent/${id}`)).model,'mock-b');checks.push('model and thinking switches');
await control('agent-tools');await prompt('export documents');
const docx=await readFile(cwd+'/outputs/spike.docx');const pdf=await readFile(cwd+'/outputs/spike.pdf');
assert.equal(docx.subarray(0,2).toString(),'PK');assert.equal(pdf.subarray(0,5).toString(),'%PDF-');
assert.ok(events.some(e=>e.type==='tool_execution_end'&&!e.isError));checks.push('export docx/pdf via real MCP');
const context=await api(`/api/sessions/${id}/context`);assert.ok(context.messages.length>=4);checks.push('persisted context after refresh');
await fetch('http://127.0.0.1:19999/control',{method:'POST',body:JSON.stringify({mode:'hang',hangMs:750})});
await api(`/api/agent/${id}`,'POST',{message:'queue first turn'});
await api(`/api/agent/${id}`,'POST',{message:'queued steer delivered',type:'steer'});
await wait(async()=>!(await api(`/api/agent/${id}`)).isStreaming);
const queuedContext=await api(`/api/sessions/${id}/context`);
const userTexts=queuedContext.messages.filter(m=>m.role==='user').map(m=>m.content[0].text);
assert.deepEqual(userTexts.slice(-2),['queue first turn','queued steer delivered']);
checks.push('steer is queued and delivered after current turn');
await control('hang');await api(`/api/agent/${id}`,'POST',{message:'cancel test'});
await api(`/api/agent/${id}`,'POST',{message:'must be discarded',type:'steer'});
await api(`/api/agent/${id}/stop`,'POST');await wait(async()=>!(await api(`/api/agent/${id}`)).isStreaming);
assert.ok(events.some(e=>e.type==='message_end'&&e.message.stopReason==='aborted') || events.filter(e=>e.type==='agent_end').length>=3);
await control('normal');await prompt('continue after stop');checks.push('stop clears queued steer, next prompt succeeds');
await api(`/api/sessions/${id}`,'PATCH',{name:'验收会话'});
assert.equal((await api('/api/sessions')).sessions.find(s=>s.id===id).name,'验收会话');checks.push('rename');
await api('/api/skills/install','POST',{name:'e2e-proof',content:'---\nname: e2e-proof\ndescription: Acceptance proof skill marker\n---\n# Proof\nUse the marker ACCEPTANCE_SKILL.'});
assert.ok((await api('/api/skills')).skills.some(s=>s.name==='e2e-proof'));checks.push('skill installation');
await mkdir(cwd+'/sessions',{recursive:true});
const legacyId='11111111-2222-4333-8444-555555555555';
await writeFile(cwd+'/sessions/legacy.jsonl',[{type:'session',version:3,id:legacyId,cwd,timestamp:new Date().toISOString()},{type:'message',id:'m1',parentId:null,message:{role:'user',content:[{type:'text',text:'legacy hello'}]},timestamp:new Date().toISOString()}].map(o=>JSON.stringify(o)+'\n').join(''));
assert.equal((await api('/api/sessions')).sessions.find(s=>s.id===legacyId).legacy,true);
assert.equal((await api(`/api/sessions/${legacyId}/context`)).messages[0].content[0].text,'legacy hello');
const rejected=await fetch(base+'/api/agent/new',{method:'POST',body:JSON.stringify({sessionId:legacyId,cwd})});assert.equal(rejected.status,400);checks.push('legacy read-only context and continuation rejection');
await api(`/api/sessions/${id}`,'DELETE');
assert.ok(!(await api('/api/sessions')).sessions.some(s=>s.id===id));checks.push('delete');
for(const bad of ['..','bad%2Fid','%2e%2e%5coutside']) {
 const r=await fetch(base+`/api/sessions/${bad}` ,{method:'DELETE'});assert.ok([400,404].includes(r.status));
}checks.push('delete traversal rejected');
controller.abort();await stream;
await mkdir('docs',{recursive:true});await writeFile('docs/dsh-app-result.json',JSON.stringify({checks,events:events.map(e=>e.type)},null,2));
console.log('PASS application API flow: '+checks.join(', '));
